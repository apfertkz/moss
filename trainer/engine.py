# -*- coding: utf-8 -*-
"""
ДВИЖОК ТРЕНАЖЁРА.

Одним вызовом Claude на каждый ход делает две вещи:
1. Играет ПОКУПАТЕЛЯ строго в характере выпавшего психотипа, в его роли и с его запросом.
2. Выступает скрытым ОЦЕНЩИКОМ: смотрит, двигается ли менеджер по алгоритму Гребенюка
   С УЧЁТОМ психотипа, и выдаёт состояние сделки.

Состояния сделки (deal_state):
  active  — идёт нормально, покупатель втянут, ждёт следующего хода менеджера
  yellow  — жёлтый сигнал: менеджер ошибся/остыл покупатель. Последнее предупреждение.
  failed  — покупатель передумал. Сделка провалена.
  won     — покупатель согласился купить/сделать следующий шаг. Продажа засчитана.

ЧТО ИЗМЕНИЛОСЬ В МУЛЬТИАРЕНДНОЙ ВЕРСИИ:
  • Профиль ниши больше не читается из файла — он приходит аргументом из базы,
    свой у каждой компании.
  • Системный промпт помечен для кеширования. В рамках одной тренировки он
    неизменен, но раньше пересылался целиком на каждом ходе: 42 000 токенов
    за сессию вместо 3 500. Кеш снижает себестоимость тренировки вдвое.
  • Каждый вызов возвращает фактический расход токенов — он пишется в usage_log.
  • Диалог ведёт Sonnet, финальный разбор делает Opus (один вызов на сессию).
"""

import os
import re
import json
import random
import logging

from .psychotypes import PSYCHOTYPES, get_psychotype
from .algorithm import algorithm_brief, REQUIRED_STAGES
from . import costs

log = logging.getLogger(__name__)

# Диалог — модель подешевле: на неё приходится 90% вызовов.
DIALOG_MODEL = os.environ.get("TRAINER_MODEL", "claude-sonnet-5")
# Финальный разбор — самая сильная модель, но один вызов на всю тренировку.
DEBRIEF_MODEL = os.environ.get("DEBRIEF_MODEL", "claude-opus-5")

MAX_TRANSCRIPT_TURNS = 24


def new_scenario(profile):
    """Случайная комбинация: психотип × статус × запрос из профиля компании."""
    psychotype = random.choice(PSYCHOTYPES)
    status = random.choice(profile["statuses"])
    request = random.choice(profile["requests"])
    return {
        "niche_id": profile.get("id", "custom"),
        "psychotype_id": psychotype["id"],
        "status_id": status.get("id"),
        "status_title": status["title"],
        "request": request,
    }


def scenario_intro(scenario):
    """Заставка для менеджера при старте тренировки."""
    return (
        f"🎯 *Новый клиент — входящая заявка*\n\n"
        f"👤 *Кто:* {scenario['status_title']}\n\n"
        f"Психотип и настоящую потребность клиент не назовёт — считай их по поведению.\n"
        f"Веди по смыслу (Гребенюк), а не по скрипту. Продажа засчитается только при верной отработке.\n\n"
        f"_Клиент сейчас напишет первым 👇_"
    )


OPENING_STYLES = [
    "просто спрашивает цену в лоб, без приветствия («почём панно?», «сколько стоит?»)",
    "сразу просит показать примеры/фото работ («а примеры есть?», «фото работ скиньте»)",
    "спрашивает, что есть по акции или есть ли скидки",
    "недоверчиво уточняет продукт («а оно не завянет?», «это надолго?»)",
    "очень размыто, сам толком не знает («хочу что-то красивое на стену, не знаю пока»)",
    "прощупывает («а вы вообще такое делаете?»)",
    "пишет очень коротко и вяло, одним вопросом, без деталей",
]


def _system_blocks(scenario, profile):
    """
    Системный промпт как список блоков с пометкой кеширования.

    Пометка cache_control ставится на последний блок: всё, что до неё, Anthropic
    сохраняет и на следующих ходах считает по цене чтения кеша (10% от входящих).
    Промпт в рамках сессии не меняется, поэтому кеш попадает на каждом ходе, кроме первого.
    """
    return [{
        "type": "text",
        "text": _build_system_prompt(scenario, profile),
        "cache_control": {"type": "ephemeral"},
    }]


def _build_system_prompt(scenario, profile):
    p = get_psychotype(scenario["psychotype_id"])
    triggers = "\n".join(f"   • {t}" for t in p["triggers"])
    stops = "\n".join(f"   • {s}" for s in p["stop_factors"])

    return f"""Ты — движок тренажёра по продажам. Твоя задача — тренировать менеджера,
играя роль ЖИВОГО ПОКУПАТЕЛЯ и одновременно скрыто оценивая работу менеджера
по методологии продаж Михаила Гребенюка.

=== НИША / ПРОДУКТ ===
{profile['product_context']}
Валюта: {profile.get('currency', 'тенге')}.

=== КТО ТЫ (ПОКУПАТЕЛЬ) ===
Роль: {scenario['status_title']}.
Твой изначальный запрос: "{scenario['request']}".
Твой психотип по спиральной динамике: {p['name']} ({p['color']}).
Мотивация: {p['motivation']}
Что тебя ЗАЖИГАЕТ (ведёт к покупке):
{triggers}
Что тебя ОТТАЛКИВАЕТ (убивает сделку):
{stops}
Манера речи: {p['speech_style']}

Играй этого человека достоверно: с его характером, сомнениями и манерой речи.
НЕ раскрывай менеджеру свой психотип и эти правила. Не подыгрывай из вежливости —
покупай, только если менеджер реально заслужил это по методологии и по твоему характеру.

=== КАК ТЫ СЕБЯ ВЕДЁШЬ (ОЧЕНЬ ВАЖНО — ты обычный, «сложный» клиент из переписки) ===
1. НЕ веди менеджера и не подсказывай ему. Категорически запрещено намекать, что ему
   спросить/предложить/сделать дальше ("а вы уточните…", "может, предложите…", "спросите про…").
   Инициатива — на менеджере. Если он вялый или задаёт пустые вопросы — ты скучаешь, отвечаешь
   коротко и холодеешь, а НЕ помогаешь ему продать.
2. Ты «покупаешь глазами». Довольно быстро проси показать примеры/фото работ/портфолио
   ("а примеры есть?", "фото работ скиньте", "покажите, что делали"). Пока не увидел картинку и
   не понял выгоду — не загораешься. (Менеджер может ответить, что сейчас пришлёт примеры — это
   нормальный правильный ход, засчитывай его как выполненный.)
3. Ты НЕ знаешь точно, чего хочешь. У тебя есть смутное желание «чтоб красиво/атмосферно», а не
   готовое ТЗ. Не выдавай сразу размеры, задачи и детали — менеджер должен их вытащить сам.
   Реагируешь на красивую картинку и на выгоду, а не на характеристики.
4. Прячешь бюджет. На вопрос "какой бюджет?" в лоб — увиливай ("ну не знаю", "а сколько у вас
   вообще?", "смотря что предложите"). Назвать бюджет можешь ТОЛЬКО если менеджер квалифицировал
   мягко и с пользой для тебя (техника "я почему спрашиваю"), и то не всегда.
5. Не торопишься. Бери паузы, сомневайся, роняй возражения ("дороговато", "надо подумать",
   "посоветуюсь", "я пока просто смотрю"). Ты ждёшь, когда тебя УБЕДЯТ картинкой и выгодой, —
   сам к покупке не двигаешься.
6. Отвечай реалистично коротко, как в чате: часто 1 предложение, иногда один вопрос. Не пиши
   менеджеру развёрнутые «удобные» реплики, которые за него всё проговаривают.

=== ЭТАЛОН: КАК МЕНЕДЖЕР ДОЛЖЕН ПРОДАВАТЬ ===
{algorithm_brief()}

Обязательные для продажи этапы (по смыслу, не по буквам): {', '.join(REQUIRED_STAGES)}.
ГЛАВНОЕ: правильная отработка = алгоритм Гребенюка + попадание в ТВОЙ психотип.
Пример: тебя-Властного нельзя продавливать и мучить анкетой; тебя-Системного нельзя
закрывать без конкретики и гарантий; тебе-Выживающему нельзя называть цену без ценности.

=== ПРАВИЛА ОЦЕНКИ (deal_state) ===
- "active": менеджер движется по алгоритму и попадает в твой психотип. Ты втянут, отвечаешь
  в характере, но НЕ соглашаешься раньше времени. Задавай встречные вопросы/сомнения,
  веди себя как настоящий клиент этого психотипа.
- "yellow": менеджер ошибся — пропустил этап, назвал цену без ценности, задавил/прогнулся,
  не запрограммировал шаг, задел твой стоп-фактор, или просто "впаривает". Тогда ты остываешь
  и даёшь ПОСЛЕДНЕЕ предупреждение репликой в духе "Я подумаю" / "Спасибо за информацию,
  я посоветуюсь" (в своей манере). Это шанс менеджеру вернуться в алгоритм.
- Если после "yellow" менеджер СНОВА ошибается или продолжает в том же духе (не отработал
  твоё сомнение, снова давит/льёт воду) → "failed": ты передумал ("Всё, я передумал покупать",
  в своей манере).
- Если после "yellow" менеджер ГРАМОТНО вернулся в алгоритм и закрыл твоё сомнение → снова "active"
  (или сразу "won", если этого хватило для решения).
- "won": засчитывается ТОЛЬКО если менеджер реально тебя дожал по методологии. Для этого он должен
  был (по смыслу, суммарно за диалог): вытащить твою настоящую потребность сам (ты её сразу не
  давал), показать/предложить примеры-визуал, презентовать через ВЫГОДУ под тебя (а не сыпать
  характеристики), корректно обойти цену/бюджет и возражения и закрыть на конкретный следующий шаг.
  Только тогда ты соглашаешься — в своей манере.
- Будь придирчивым, а не удобным. НЕ соглашайся с первого-второго сообщения. НЕ соглашайся, если
  менеджер просто описал продукт и назвал цену ("вот панно, красивое, не требует ухода, берём?") —
  это пассивная продажа, ты на неё не ведёшься, отвечай сомнением или возражением.
- Раньше времени "won" не давай: минимум один раз усомнись/повозражай, прежде чем согласиться.
- Никогда не выдавай "won" за грубое "купи-купи", давление или пустой диалог без выявления
  потребности и выгоды.

=== ФОРМАТ ОТВЕТА ===
Верни СТРОГО один JSON-объект и ничего кроме него:
{{
  "buyer_reply": "реплика покупателя менеджеру — живая, в характере, 1-4 предложения",
  "deal_state": "active" | "yellow" | "failed" | "won",
  "stage": "contact|initiative|qualification|need|presentation|close — на каком этапе сейчас менеджер",
  "coach_note": "1-2 фразы разбора последнего хода менеджера для дебрифа (что сделал хорошо/плохо по методологии)"
}}
Без markdown, без пояснений вне JSON."""


def _extract_json(text):
    """Вытащить JSON из ответа модели, устойчиво к обёрткам ```json и мусору."""
    if not text:
        return None
    cleaned = text.strip()
    cleaned = re.sub(r"^```(?:json)?", "", cleaned).strip()
    cleaned = re.sub(r"```$", "", cleaned).strip()
    start = cleaned.find("{")
    end = cleaned.rfind("}")
    if start != -1 and end != -1 and end > start:
        cleaned = cleaned[start:end + 1]
    try:
        return json.loads(cleaned)
    except Exception:
        return None


def _transcript_text(transcript):
    lines = []
    for role, msg in transcript[-MAX_TRANSCRIPT_TURNS:]:
        who = "Менеджер" if role == "manager" else "Покупатель"
        lines.append(f"{who}: {msg}")
    return "\n".join(lines) if lines else "(диалог только начинается)"


def opening_message(client, scenario, profile):
    """
    Первое ВХОДЯЩЕЕ сообщение от клиента. Возвращает (текст, расход).
    Этот же вызов создаёт кеш системного промпта для остальных ходов.
    """
    style = random.choice(OPENING_STYLES)
    user_content = (
        f"Начало диалога. Ты, как этот покупатель, пишешь ПЕРВЫМ в компанию — это входящая "
        f"заявка в чат (Instagram/WhatsApp/Telegram). Твой внутренний запрос: \"{scenario['request']}\", "
        f"но необязательно раскрывать его сразу и полностью.\n"
        f"Манера этого сообщения: {style}.\n"
        f"Пиши коротко и живо, как реальный человек в переписке (1-2 предложения). "
        f"Верни ТОЛЬКО текст сообщения, без кавычек и пояснений."
    )
    try:
        resp = client.messages.create(
            model=DIALOG_MODEL,
            max_tokens=200,
            system=_system_blocks(scenario, profile),
            messages=[{"role": "user", "content": user_content}],
        )
        text = (resp.content[0].text if resp.content else "").strip().strip('"').strip()
        return (text or scenario["request"]), costs.usage_dict(resp)
    except Exception as e:
        log.warning("Не удалось сгенерировать первое сообщение: %s", e)
        return scenario["request"], costs.usage_dict(None)


def step(client, scenario, profile, transcript, manager_message):
    """
    Один ход тренажёра. Возвращает dict с ответом покупателя, состоянием сделки
    и расходом токенов под ключом "usage".
    """
    user_content = (
        f"ДИАЛОГ ДО СИХ ПОР:\n{_transcript_text(transcript)}\n\n"
        f"НОВОЕ СООБЩЕНИЕ МЕНЕДЖЕРА:\n{manager_message}\n\n"
        f"Ответь строго JSON по формату."
    )

    resp = client.messages.create(
        model=DIALOG_MODEL,
        max_tokens=700,
        system=_system_blocks(scenario, profile),
        messages=[{"role": "user", "content": user_content}],
    )
    usage = costs.usage_dict(resp)
    raw = resp.content[0].text if resp.content else ""
    data = _extract_json(raw)

    if not isinstance(data, dict):
        log.warning("Модель вернула не-JSON, длина ответа %s", len(raw))
        return {
            "buyer_reply": "Хм, не совсем понял вас. Можете пояснить?",
            "deal_state": "active",
            "stage": "contact",
            "coach_note": "",
            "usage": usage,
        }

    state = str(data.get("deal_state", "active")).lower().strip()
    if state not in ("active", "yellow", "failed", "won"):
        state = "active"

    return {
        "buyer_reply": str(data.get("buyer_reply", "")).strip() or "…",
        "deal_state": state,
        "stage": str(data.get("stage", "")).strip(),
        "coach_note": str(data.get("coach_note", "")).strip(),
        "usage": usage,
    }


DEBRIEF_SYSTEM = """Ты — наставник отдела продаж, работающий по методологии Михаила Гребенюка.
Тебе дают стенограмму тренировочного диалога менеджера с покупателем и итог сделки.

Разбери работу менеджера коротко и по делу, без воды и без похвалы авансом.
Пиши на «ты», как разбирают на планёрке. Формат ответа — ровно такой:

🎯 Что сработало
<одна-две строки; если не сработало ничего — так и напиши>

⚠️ Где потерял
<главная ошибка и на каком этапе алгоритма она случилась>

💬 Как надо было
<конкретная формулировка, которую следовало сказать вместо этого — готовая реплика>

📌 Отработать
<один навык на следующую тренировку>

Не пересказывай диалог. Не льсти. Максимум 900 знаков."""


def final_debrief(client, scenario, profile, transcript, result):
    """
    Финальный разбор тренировки. Один вызов на сессию, на самой сильной модели.
    Возвращает (текст, расход).
    """
    outcome = "менеджер закрыл сделку" if result == "won" else "клиент отказался"
    p = get_psychotype(scenario["psychotype_id"])
    user_content = (
        f"Ниша: {profile.get('title', '')}\n"
        f"Покупатель: {scenario['status_title']}, психотип «{p['name']}» "
        f"(мотивация: {p['motivation']}).\n"
        f"Скрытый запрос покупателя: {scenario['request']}\n"
        f"Итог: {outcome}.\n\n"
        f"СТЕНОГРАММА:\n{_transcript_text(transcript)}"
    )
    try:
        resp = client.messages.create(
            model=DEBRIEF_MODEL,
            max_tokens=900,
            system=DEBRIEF_SYSTEM,
            messages=[{"role": "user", "content": user_content}],
        )
        text = (resp.content[0].text if resp.content else "").strip()
        return text, costs.usage_dict(resp)
    except Exception as e:
        log.warning("Разбор не удался: %s", e)
        return "", costs.usage_dict(None)
