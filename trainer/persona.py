# -*- coding: utf-8 -*-
"""
Персона покупателя: живой человек поверх психотипа.

Психотип отвечает на вопрос «как этот человек принимает решение».
Персона — на вопрос «кто он и как он пишет». Без неё менеджер разговаривает
с ролью («Директор ресторана»), а не с человеком, и через две тренировки
начинает видеть шаблон.

Всё здесь собирается в Python, без обращения к модели: это ноль стоимости,
полный контроль над разнообразием и воспроизводимость. Модель получает
готовую персону в системном промпте и просто её играет.
"""

import random

# --- Имена -------------------------------------------------------------------
